public class Jaula {
    private int numero;
    private float tamanio;
    private String sona;
    private String ocupante;

    public Jaula(int numero, float tamanio, String sona, String ocupante) {
        this.numero = numero;
        this.tamanio = tamanio;
        this.sona = sona;
        this.ocupante = ocupante;
    }
}
